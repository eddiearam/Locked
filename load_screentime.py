#!/usr/bin/env python3
"""Create the agreed screen-time schema and load data/locked_screentime_full.csv.

Re-runs replace existing rows so tables never accumulate duplicates.
"""

import csv
import os
import sys
from pathlib import Path

import psycopg2
from dotenv import load_dotenv
from psycopg2.extras import execute_values

ROOT = Path(__file__).resolve().parent
CSV_PATH = ROOT / "data" / "locked_screentime_full.csv"

DDL = """
DROP TABLE IF EXISTS usage_observation CASCADE;
DROP TABLE IF EXISTS app_user CASCADE;
DROP TABLE IF EXISTS behavior_class CASCADE;
DROP TABLE IF EXISTS operating_system CASCADE;

CREATE TABLE operating_system (
    os_id   SMALLINT PRIMARY KEY,
    name    VARCHAR(16) NOT NULL UNIQUE
);

CREATE TABLE behavior_class (
    class_id    SMALLINT PRIMARY KEY,
    rank        SMALLINT NOT NULL UNIQUE,
    label       VARCHAR(64),
    CONSTRAINT behavior_class_rank_range CHECK (rank BETWEEN 1 AND 5)
);

CREATE TABLE app_user (
    user_id     INTEGER PRIMARY KEY,
    os_id       SMALLINT NOT NULL REFERENCES operating_system (os_id),
    age_years   SMALLINT NOT NULL,
    CONSTRAINT app_user_age_range CHECK (age_years BETWEEN 18 AND 120)
);

CREATE TABLE usage_observation (
    observation_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                     INTEGER NOT NULL UNIQUE REFERENCES app_user (user_id),
    app_usage_minutes_per_day   INTEGER NOT NULL CHECK (app_usage_minutes_per_day >= 0),
    screen_on_hours_per_day     NUMERIC(4, 1) NOT NULL
        CHECK (screen_on_hours_per_day >= 0 AND screen_on_hours_per_day <= 24),
    apps_installed_count        SMALLINT NOT NULL CHECK (apps_installed_count >= 0),
    behavior_class_id           SMALLINT NOT NULL REFERENCES behavior_class (class_id)
);
"""

OS_SEED = [(1, "Android"), (2, "iOS")]
BEHAVIOR_SEED = [(n, n, None) for n in range(1, 6)]
TABLES = ["operating_system", "behavior_class", "app_user", "usage_observation"]


def database_url() -> str:
    load_dotenv(ROOT / ".env", override=True)
    url = ""
    for key in ("DATABASE_URL", "Database_URL", "DATABASE_PUBLIC_URL"):
        url = (os.getenv(key) or "").strip().strip("'").strip('"')
        if url:
            break
    if not url:
        sys.exit(
            "DATABASE_URL is missing from .env. Paste Railway's DATABASE_PUBLIC_URL "
            "(host should end in proxy.rlwy.net, not railway.internal)."
        )
    if "railway.internal" in url:
        sys.exit(
            "DATABASE_URL looks like Railway's private host (railway.internal). "
            "Use DATABASE_PUBLIC_URL locally."
        )
    return url


def load_csv_rows():
    """Return unique users and observations keyed by user_id (last row wins)."""
    os_by_name = {name: os_id for os_id, name in OS_SEED}
    users = {}
    observations = {}

    with CSV_PATH.open(newline="") as f:
        reader = csv.DictReader(f)
        extra = set(reader.fieldnames or []) & {"tools", "availability"}
        if extra:
            raise ValueError(
                f"Unexpected multi-value columns {sorted(extra)}; "
                "the agreed screen-time schema has no bridge tables."
            )
        for row in reader:
            os_name = row["Operating_System"].strip()
            if os_name not in os_by_name:
                raise ValueError(f"Unknown operating system: {os_name!r}")

            user_id = int(row["User_ID"])
            users[user_id] = (user_id, os_by_name[os_name], int(row["Age"]))
            observations[user_id] = (
                user_id,
                int(row["App_Usage_Time"]),
                float(row["Screen_On_Time"]),
                int(row["Number_of_Apps_Installed"]),
                int(row["User_Behavior_Class"]),
            )

    return list(users.values()), list(observations.values())


def main() -> None:
    if not CSV_PATH.exists():
        sys.exit(f"CSV not found: {CSV_PATH}")

    users, observations = load_csv_rows()
    conn = psycopg2.connect(database_url())
    try:
        with conn:
            with conn.cursor() as cur:
                cur.execute(DDL)

                execute_values(
                    cur,
                    """
                    INSERT INTO operating_system (os_id, name) VALUES %s
                    ON CONFLICT (os_id) DO UPDATE SET name = EXCLUDED.name
                    """,
                    OS_SEED,
                )
                execute_values(
                    cur,
                    """
                    INSERT INTO behavior_class (class_id, rank, label) VALUES %s
                    ON CONFLICT (class_id) DO UPDATE SET
                        rank = EXCLUDED.rank,
                        label = EXCLUDED.label
                    """,
                    BEHAVIOR_SEED,
                )
                execute_values(
                    cur,
                    """
                    INSERT INTO app_user (user_id, os_id, age_years) VALUES %s
                    ON CONFLICT (user_id) DO UPDATE SET
                        os_id = EXCLUDED.os_id,
                        age_years = EXCLUDED.age_years
                    """,
                    users,
                )
                execute_values(
                    cur,
                    """
                    INSERT INTO usage_observation (
                        user_id,
                        app_usage_minutes_per_day,
                        screen_on_hours_per_day,
                        apps_installed_count,
                        behavior_class_id
                    ) VALUES %s
                    ON CONFLICT (user_id) DO UPDATE SET
                        app_usage_minutes_per_day = EXCLUDED.app_usage_minutes_per_day,
                        screen_on_hours_per_day = EXCLUDED.screen_on_hours_per_day,
                        apps_installed_count = EXCLUDED.apps_installed_count,
                        behavior_class_id = EXCLUDED.behavior_class_id
                    """,
                    observations,
                )

                print("Row counts:")
                for table in TABLES:
                    cur.execute(f"SELECT COUNT(*) FROM {table}")
                    print(f"  {table}: {cur.fetchone()[0]}")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
